// Writes src/ts-identifier-table.ts: which code points every TypeScript the package supports reads
// as an identifier.
//
//     node scripts/generate-identifier-table.mjs      (or: npm run generate:identifiers)
//
// A binding is read by the TypeScript compiler, so what may be written as an identifier is what its
// scanner accepts, which is a table of its own and not the one Node's `\p{ID_Start}` or Souther's
// alphabet is. That table grows from one TypeScript to the next, so what a binding may hold is what
// the oldest TypeScript supported reads (OLDEST, which README.md names) and the one this package is
// built with does too. The oldest is fetched here and nowhere else, which is the only time this needs
// the network; the table is then written down so that the generator needs no TypeScript and writes the
// same names whichever Node runs it. test/identifier.test.ts holds the table to the installed
// TypeScript for every code point.

import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";

/** The oldest TypeScript a binding is written for. */
const OLDEST = "5.7.3";

const here = createRequire(import.meta.url);
const ts = here("typescript");
const TARGET = ts.ScriptTarget.ES2020;

/** The TypeScript `version`, fetched into a directory of its own, since it is not the one installed. */
function fetched(version) {
  const at = mkdtempSync(join(tmpdir(), "typescript-"));
  const [archive] = JSON.parse(execFileSync("npm", ["pack", `typescript@${version}`, "--json", "--pack-destination", at],
    { encoding: "utf8" })).map((each) => each.filename);
  execFileSync("tar", ["xzf", join(at, archive), "-C", at]);
  return createRequire(join(at, "package", "x.js"))("./lib/typescript.js");
}

const oldest = fetched(OLDEST);
if (oldest.version !== OLDEST) {
  throw new Error(`asked for TypeScript ${OLDEST} and got ${oldest.version}`);
}

/** The ranges of code points `accepts` holds for, as a flat list of first, last, first, last… */
function rangesOf(accepts) {
  const flat = [];
  let first = -1;
  for (let cp = 0; cp <= 0x10ffff + 1; cp++) {
    const held = cp <= 0x10ffff && accepts(cp, TARGET);
    if (held && first < 0) {
      first = cp;
    } else if (!held && first >= 0) {
      flat.push(first, cp - 1);
      first = -1;
    }
  }
  return flat;
}

function written(name, flat) {
  const lines = [];
  for (let i = 0; i < flat.length; i += 8) {
    lines.push("  " + flat.slice(i, i + 8).map((cp) => "0x" + cp.toString(16)).join(", ") + ",");
  }
  return `const ${name}: readonly number[] = [\n${lines.join("\n")}\n];\n`;
}

const out = `// Generated by scripts/generate-identifier-table.mjs from TypeScript ${OLDEST} and ${ts.version} (ES2020 and later).
// Do not edit: generate it again.

${written("START", rangesOf((cp, target) => ts.isIdentifierStart(cp, target) && oldest.isIdentifierStart(cp, target)))}
${written("PART", rangesOf((cp, target) => ts.isIdentifierPart(cp, target) && oldest.isIdentifierPart(cp, target)))}
/** The oldest TypeScript the table is for: every one from it on reads what the table holds. */
export const OLDEST_TYPESCRIPT = ${JSON.stringify(OLDEST)};

function within(ranges: readonly number[], codePoint: number): boolean {
  let low = 0;
  let high = ranges.length / 2 - 1;
  while (low <= high) {
    const middle = (low + high) >> 1;
    if (codePoint < ranges[2 * middle]!) {
      high = middle - 1;
    } else if (codePoint > ranges[2 * middle + 1]!) {
      low = middle + 1;
    } else {
      return true;
    }
  }
  return false;
}

/** Whether TypeScript reads \`codePoint\` as the start of an identifier. */
export function isIdentifierStart(codePoint: number): boolean {
  return within(START, codePoint);
}

/** Whether TypeScript reads \`codePoint\` as a part of an identifier after its first. */
export function isIdentifierPart(codePoint: number): boolean {
  return within(PART, codePoint);
}
`;
writeFileSync(join(import.meta.dirname, "..", "src", "ts-identifier-table.ts"), out);
