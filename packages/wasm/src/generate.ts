// A TypeScript binding of a Souther program, written from what its module says it offers.
//
// Everything written here is read off the module's surface: the types its values cross as, the
// behaviors it offers, what it reaches out for, and the types a caller may read a value of on its
// own. Nothing about a model is decided here, so a case renamed in the model is a type renamed in
// the binding, and a page that still names the old one does not compile.

import { type Declaration, type Form, keyOf as key, type Shape, type Surface, tagOf } from "./surface.ts";
import { namesOf as declarationNames, parameterNames } from "./names.ts";

/**
 * What the binding itself declares at its top, which a model's declaration does not displace.
 *
 * Every one of these is written into the binding from here and only from here, and the binding names
 * nothing else at its top but the types `namesOf` hands out: none of TypeScript's own (`Record`,
 * `Promise`), which a model's type of the same name would stand in for. So a name the binding comes
 * to declare is reserved by being declared, and no list of reserved names can fall behind it.
 */
const OWN = {
  runtime: "souther",
  fingerprint: "FINGERPRINT",
  supplied: "Supplied",
  bound: "Bound",
  load: "load",
} as const;
const R = OWN.runtime;

/** A value with no field, written without naming TypeScript's `Readonly` or `Record`. */
const NOTHING = "{ readonly [key: string]: never }";

/**
 * The binding of a module whose surface is `surface`, as TypeScript source.
 *
 * What the model names is the binding's to call whatever it likes only where a property says it: a
 * module, a behavior and a type a value is read as are each a property, under the name the model
 * gives it, so `bound.modules.cart.price`, `bound.decode.cart.Sku` and `bound.form.cart.Cart`. What is declared at the top
 * — a type for each declaration — is named by `namesOf`, apart from what TypeScript reserves and what
 * the binding declares itself, and the runtime is read through one name, so no type of the model's
 * stands in for one of the runtime's.
 *
 * @param fingerprint what identifies the surface (`fingerprintOf`), which the binding refuses any
 *     other module than one carrying
 * @param runtime what the binding imports the runtime as
 */
export function bindingFor(surface: Surface, fingerprint: string, runtime = "@souther-lang/wasm"): string {
  const names = declarationNames(surface.declarations, Object.values(OWN));
  const declared = new Map(surface.declarations.map((each) => [key(each), each]));
  const typeOf = (shape: Shape): string => written(shape, names, declared);
  const out: string[] = [
    "// Generated by @souther-lang/wasm from a module's souther:surface. Do not edit: generate it again",
    "// from the module instead.",
    "",
    `import * as ${R} from ${JSON.stringify(runtime)};`,
    "",
    "/** What identifies the surface this binding was generated from; a module carrying another is refused. */",
    `export const ${OWN.fingerprint} = ${JSON.stringify(fingerprint)};`,
    "",
  ];

  for (const declaration of surface.declarations) {
    out.push(`/** \`${inComment(`${declaration.module}.${declaration.name}`)}\`${declaration.published === false ? ", which its module keeps" : ""}. */`);
    out.push(`export type ${names.get(key(declaration))} = ${declarationType(declaration, typeOf, names, declared)};`);
    out.push("");
  }

  // What the host has to supply is every behavior the program reaches out for, whether its module
  // publishes it or keeps it: a kept one is reached for all the same.
  const reaching = surface.modules.flatMap((module) => module.behaviors
    .filter((behavior) => behavior.reachOut !== undefined)
    .map((behavior) => ({ behavior, named: `${module.name}.${behavior.name}` })));
  out.push("/** What answers each behavior the program reaches out for. */");
  out.push(`export interface ${OWN.supplied} {`);
  for (const { behavior, named } of reaching) {
    out.push(`  readonly ${JSON.stringify(named)}: (${parameters(behavior.parameters, typeOf)}) => ${typeOf(behavior.answers)};`);
  }
  out.push("}");
  out.push("");

  // What a caller may call is every behavior a module publishes, whoever answers it: one the host
  // answers is called through the module all the same, which reads what it is handed as the
  // model's types before it reaches out.
  const offered = surface.modules.map((module) => ({
    module,
    behaviors: module.behaviors.filter((behavior) => behavior.export !== undefined),
  }));
  const decodable = new Map<string, Declaration[]>();
  for (const declaration of surface.declarations.filter((each) => each.decode !== undefined)) {
    decodable.set(declaration.module, [...decodable.get(declaration.module) ?? [], declaration]);
  }

  out.push("/** The program, loaded: each module's behaviors, and Raoh decoders of each type a value can be read as on its own, of a value and of what a form gives. */");
  out.push(`export interface ${OWN.bound} {`);
  out.push(`  readonly program: ${R}.Program;`);
  out.push("  readonly modules: {");
  for (const { module, behaviors } of offered) {
    out.push(`    readonly ${property(module.name)}: {`);
    for (const behavior of behaviors) {
      out.push(`      ${property(behavior.name)}(${parameters(behavior.parameters, typeOf)}): ${R}.Reading<${typeOf(behavior.answers)}>;`);
    }
    out.push("    };");
  }
  out.push("  };");
  for (const [reading, decoderType] of [["decode", "Decoder"], ["form", "FormDecoder"]]) {
    out.push(`  readonly ${reading}: {`);
    for (const [module, declarations] of decodable) {
      out.push(`    readonly ${property(module)}: {`);
      for (const declaration of declarations) {
        out.push(`      readonly ${property(declaration.name)}: ${R}.${decoderType}<${names.get(key(declaration))}>;`);
      }
      out.push("    };");
    }
    out.push("  };");
  }
  out.push("}");
  out.push("");

  const optional = reaching.length === 0 ? " = {}" : "";
  out.push("/** Loads the module this binding was generated from, and refuses any other. */");
  // What it answers is a promise of the binding, which TypeScript says without being told: the
  // binding names no global type, and a model's `Promise` cannot stand in for one it does not name.
  out.push(`export async function ${OWN.load}(source: ${R}.Source, supplied: ${OWN.supplied}${optional}) {`);
  out.push(`  const program = await ${R}.load(source, supplied as unknown as ${R}.Supplied, ${OWN.fingerprint});`);
  out.push(`  const bound: ${OWN.bound} = {`);
  out.push("    program,");
  out.push("    modules: {");
  for (const { module, behaviors } of offered) {
    out.push(`      ${property(module.name)}: {`);
    for (const behavior of behaviors) {
      // The arguments are named by place and nothing else, so no name the model gave a parameter
      // stands for `program` here.
      const names = behavior.parameters.map((_, at) => `argument${at}`).join(", ");
      out.push(`        ${property(behavior.name)}: (${names}) => program.call(${JSON.stringify(behavior.export as string)}, [${names}]),`);
    }
    out.push("      },");
  }
  out.push("    },");
  for (const [reading, made] of [["decode", "decoder"], ["form", "formDecoder"]]) {
    out.push(`    ${reading}: {`);
    for (const [module, declarations] of decodable) {
      out.push(`      ${property(module)}: {`);
      for (const declaration of declarations) {
        out.push(`        ${property(declaration.name)}: program.${made}(${JSON.stringify(key(declaration))}),`);
      }
      out.push("      },");
    }
    out.push("    },");
  }
  out.push("  };");
  out.push("  return bound;");
  out.push("}");
  return out.join("\n") + "\n";
}

/**
 * `text` as it can stand in a comment: a module is read as it is, and a name in one is not the
 * binding's to trust to end a comment where it meant to.
 */
function inComment(text: string): string {
  return text.replace(/\*\//g, "*\\/").replace(/[\r\n\u2028\u2029]/g, " ");
}

/** A property's name as TypeScript writes it: bare where it can be, quoted where it cannot. */
function property(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

/**
 * A signature's parameters, under the names the model gave them where TypeScript can write those,
 * which is what a caller reads off the signature; under another where it cannot.
 */
function parameters(
  declared: readonly { readonly name: string | null; readonly type: Shape }[],
  typeOf: (shape: Shape) => string,
): string {
  const names = parameterNames(declared.map((each) => each.name));
  return declared.map((each, at) => `${names[at]}: ${typeOf(each.type)}`).join(", ");
}

function declarationType(
  declaration: Declaration,
  typeOf: (shape: Shape) => string,
  names: Map<string, string>,
  declared: Map<string, Declaration>,
): string {
  switch (declaration.is) {
    case "product": {
      // An optional field is the boundary's to read as nothing where it is left out and where it
      // is written as null, so its type says both: what a type says is what the boundary takes, and
      // a field typed narrower would refuse a value every backend reads. That a module leaves it out
      // when it writes one is how it writes, and a reader handling both loses nothing.
      const fields = declaration.fields.map((field) => field.type.is === "option"
        ? `readonly ${property(field.name)}?: ${typeOf(field.type)}`
        : `readonly ${property(field.name)}: ${typeOf(field.type)}`);
      return fields.length === 0 ? NOTHING : `{ ${fields.join("; ")} }`;
    }
    case "newtype":
      return typeOf(declaration.wraps);
    case "unit":
      return NOTHING;
    case "sum":
      return alternatives(declaration.cases, declaration.form, names, declared, typeOf);
  }
}

/** A set of alternatives, as the form it travels in writes each of them. */
function alternatives(
  cases: readonly Shape[],
  form: Form,
  names: Map<string, string>,
  declared: Map<string, Declaration>,
  typeOf: (shape: Shape) => string,
): string {
  if (form.is === "enumeration") {
    return cases.map((each) => JSON.stringify(tagOf(each))).join(" | ");
  }
  return cases.map((each) => {
    const tag = `readonly ${property(form.tag)}: ${JSON.stringify(tagOf(each))}`;
    if (each.is === "declared") {
      const declaration = declared.get(key(each));
      if (declaration?.is === "unit") {
        return `{ ${tag} }`;
      }
      if (declaration?.is === "product") {
        return `({ ${tag} } & ${names.get(key(each))})`;
      }
    }
    // A newtype or a primitive keeps what it is written as, under a key of its own beside the tag.
    return `{ ${tag}; readonly ${property(form.contents)}: ${typeOf(each)} }`;
  }).join(" | ");
}

function written(shape: Shape, names: Map<string, string>, declared: Map<string, Declaration>): string {
  const typeOf = (inner: Shape): string => written(inner, names, declared);
  switch (shape.is) {
    case "scalar":
      switch (shape.scalar) {
        // As Raoh's long() and decimal() give them, so nothing counted or priced is rounded.
        case "int":
          return "bigint";
        case "decimal":
          return `${R}.Decimal`;
        case "bool":
          return "boolean";
        default:
          return "string";
      }
    case "declared":
      return names.get(key(shape)) ?? "unknown";
    case "list":
    case "set":
      return `readonly (${typeOf(shape.of)})[]`;
    case "map":
      return `{ readonly [key: string]: ${typeOf(shape.value)} }`;
    case "option":
      return `${typeOf(shape.of)} | null`;
    case "union":
      return alternatives(shape.crossing.cases, shape.crossing.form, names, declared, typeOf);
  }
}
